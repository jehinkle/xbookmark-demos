import { describe, it, expect, afterAll } from 'vitest'
import { readFileSync, writeFileSync } from 'node:fs'
import { nT, nZ, powerT, powerZ, nStandard } from '../src/stats/standard.js'
import { assurance, rule, nBayes } from '../src/stats/bayes.js'
import { simPower, simGrid } from '../src/stats/sim.js'

const cases = JSON.parse(readFileSync(new URL('./cases.json', import.meta.url)))
const refFile = JSON.parse(readFileSync(new URL('./reference.json', import.meta.url)))
const ref = Object.fromEntries(refFile.results.map(r => [r.id, r]))
const rows = []
const cmp = (c, what, js, r, tol, kind = 'deterministic') => {
  const d = Math.abs(js - r); rows.push({ id: c.id, desc: c.desc, what, js, ref: r, diff: d, tol, kind, pass: d <= tol }); expect(d).toBeLessThanOrEqual(tol)
}
const S = c => ({ endpoint: c.endpoint || (c.pC !== undefined ? 'binary' : 'continuous'), delta: c.delta ?? 5, sd: c.sd ?? 10, pC: c.pC ?? 0.3, pT: c.pT ?? 0.45, alpha: c.alpha ?? 0.05, power: c.power ?? 0.8, ratio: c.ratio ?? 1 })
const mcTol = (p, n1, n2) => 3 * Math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))

describe('JS engine vs R reference', () => {
  for (const c of cases) it(`${c.id}: ${c.desc}`, () => {
    const R = ref[c.id], s = S(c)
    if (c.kind === 't_n') cmp(c, 'n per arm (power.t.test)', nT(s), R.n, 1e-3)
    if (c.kind === 't_power' || c.kind === 't_power_ratio') cmp(c, c.ratio ? 'power (R noncentral pt)' : 'power (power.t.test)', powerT(s, c.n), R.power, 1e-6)
    if (c.kind === 'z_n') cmp(c, 'n per arm (normal formula in R)', nZ(s), R.n, 1e-6)
    if (c.kind === 'prop_n') cmp(c, 'n per arm (power.prop.test)', nZ(s), R.n, 1e-3)
    if (c.kind === 'prop_power' || c.kind === 'prop_power_ratio') cmp(c, c.ratio ? 'power (R pooled-z formula)' : 'power (power.prop.test)', powerZ(s, c.n), R.power, 1e-6)
    if (c.kind === 'assurance') {
      const d = c.endpoint === 'continuous' ? c.delta : Math.abs(c.pT - c.pC)
      const b = { priorMeanMult: c.mu / d, priorSdMult: c.tau / d }
      cmp(c, 'assurance (R integrate over prior)', assurance(s, b, c.n), R.assurance, 1e-6)
    }
    if (c.kind === 'bayes') {
      const b = { n0: c.n0, analysisMean: c.mean, gamma: c.gamma, priorMeanMult: 1, priorSdMult: 0.75 }
      const n = nBayes(s, b), r = rule(s, b, n)
      cmp(c, 'n per arm (R conjugate update + uniroot)', n, R.n, 0)
      cmp(c, 'P(success | design effect) (R)', r.pSuccess, R.pSuccess, 1e-6)
      cmp(c, 'type I error (R)', r.typeI, R.typeI, 1e-6)
      if (R.simTypeI !== undefined) {
        cmp(c, `type I error vs R simulation (${R.nSim.toLocaleString()} trials)`, r.typeI, R.simTypeI, 3 * Math.sqrt(r.typeI * (1 - r.typeI) / R.nSim), 'Monte Carlo')
        cmp(c, `P(success) vs R simulation (${R.nSim.toLocaleString()} trials)`, r.pSuccess, R.simPSuccess, 3 * Math.sqrt(r.pSuccess * (1 - r.pSuccess) / R.nSim), 'Monte Carlo')
      }
    }
    if (c.kind === 'sim') {
      const N = 20000, js = simPower(s, c.n, N, 20261119, { dropout: c.dropout, shape: c.shape })
      cmp(c, `simulated power, JS vs R (${N.toLocaleString()} each, different RNGs)`, js.power, R.power, mcTol(R.power, N, R.nSim), 'Monte Carlo')
    }
  })
  it('SN: simulation-search n agrees with power.t.test / power.prop.test', () => {
    for (const [id, c] of [['T1', cases.find(x => x.id === 'T1')], ['P1', cases.find(x => x.id === 'P1')]]) {
      const s = S(c), g = simGrid(s, 4000, 20261119)
      cmp({ id: 'SN-' + id, desc: `Simulation search (11 n values x 4,000 trials, probit fit) for ${id}` }, 'fitted n per arm vs R', g.nFit, ref[id].n, id === 'T1' ? 3 : 8, 'Monte Carlo')
    }
  }, 60000)
  afterAll(() => {
    writeFileSync(new URL('./agreement.json', import.meta.url), JSON.stringify(rows, null, 1))
    const fmt = x => Number.isInteger(x) ? String(x) : Math.abs(x) >= 1 ? x.toFixed(4) : x.toPrecision(6)
    const det = rows.filter(r => r.kind === 'deterministic'), mc = rows.filter(r => r.kind !== 'deterministic')
    const maxDet = Math.max(...det.map(r => r.diff)), nCases = new Set(rows.map(r => r.id)).size
    const md = [`# Validation agreement`, '',
      `JS engine (\`src/stats/\`) vs ${refFile.meta.R} (base R \`power.t.test\`, \`power.prop.test\`, \`integrate\`, \`uniroot\`, seeded simulation with ${refFile.meta.nSim.toLocaleString()} trials, seed ${refFile.meta.seed}). Generated by \`npm test\` from \`reference.json\`, which \`Rscript validation/reference.R\` creates.`, '',
      `**${rows.filter(r => r.pass).length}/${rows.length} comparisons within tolerance across ${nCases} cases.**`, '',
      `- Deterministic values: ${det.filter(r => r.pass).length}/${det.length} within tolerance; largest absolute difference ${maxDet.toExponential(2)}.`,
      `- Monte Carlo values: ${mc.filter(r => r.pass).length}/${mc.length} within tolerance (3 combined standard errors; the JS and R simulations use different random number generators, so these agree statistically, not digit for digit).`, '',
      '| Case | Description | Quantity | JS | Reference | |diff| | Tol | Type |', '|---|---|---|---|---|---|---|---|',
      ...rows.map(r => `| ${r.id} | ${r.desc} | ${r.what} | ${fmt(r.js)} | ${fmt(r.ref)} | ${r.diff.toExponential(1)} | ${r.tol} | ${r.kind}${r.pass ? '' : ' **FAIL**'} |`), '']
    writeFileSync(new URL('./AGREEMENT.md', import.meta.url), md.join('\n'))
  })
})
