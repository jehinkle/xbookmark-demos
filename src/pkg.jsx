import { useState } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { jsPDF } from 'jspdf'
import { svg2pdf } from 'svg2pdf.js'
import { km, at, atRisk, logrank, ARMS, PARAMS } from './km.js'
import { Plot } from './App.jsx'

const STUDY = 'Protocol XNB-301 (MOCK)'
const f1 = v => v == null ? 'NE' : v.toFixed(1), pct = v => (v * 100).toFixed(1)
export const DEFAULT_MANIFEST = [
  { id: 't-os', kind: 'Table', param: 'OS', number: '14.2.1.1', title: 'Kaplan-Meier Estimates of Overall Survival', pop: 'Intent-to-Treat Population', include: true },
  { id: 't-pfs', kind: 'Table', param: 'PFS', number: '14.2.1.2', title: 'Kaplan-Meier Estimates of Progression-Free Survival', pop: 'Intent-to-Treat Population', include: true },
  { id: 'f-os', kind: 'Figure', param: 'OS', number: '14.2.1.1', title: 'Kaplan-Meier Plot of Overall Survival', pop: 'Intent-to-Treat Population', include: true },
  { id: 'f-pfs', kind: 'Figure', param: 'PFS', number: '14.2.1.2', title: 'Kaplan-Meier Plot of Progression-Free Survival', pop: 'Intent-to-Treat Population', include: true },
  { id: 'l-adtte', kind: 'Listing', param: 'ALL', number: '16.2.6.1', title: 'Time-to-Event Analysis Data (ADTTE excerpt, first 40 subjects)', pop: 'Intent-to-Treat Population', include: true },
]
const LIST_COLS = ['USUBJID', 'TRT01P', 'PARAMCD', 'STARTDT', 'ADT', 'AVAL', 'CNSR', 'EVNTDESC'], PER_PAGE = 26
const fitsFor = (data, param, shell) => shell.arms.map(a => { const rows = data.filter(r => r.PARAMCD === param && r.TRT01P === a); return { a, i: ARMS.indexOf(a), rows, k: km(rows) } })
const listingRows = data => { const ids = [...new Set(data.map(r => r.USUBJID))].slice(0, 40); return data.filter(r => ids.includes(r.USUBJID)) }
const pagesOf = (o, data) => o.kind === 'Listing' ? Math.ceil(listingRows(data).length / PER_PAGE) : 1

function tableRows(fits, lms, lr) {
  const R = [['', ...fits.map(f => `${f.a} (N=${f.k.N})`), 'h'], ['Subjects with event, n (%)', ...fits.map(f => `${f.k.events} (${pct(f.k.events / f.k.N)})`)],
    ['Censored, n (%)', ...fits.map(f => `${f.k.censored} (${pct(f.k.censored / f.k.N)})`)], ['Time to event (months)', ...fits.map(() => ''), 's'],
    ['   Median (95% CI)', ...fits.map(f => `${f1(f.k.median)} (${f1(f.k.mlo)}, ${f1(f.k.mhi)})`)], ['Event-free rate, % (95% CI)', ...fits.map(() => ''), 's']]
  for (const t of lms) R.push([`   ${t} months`, ...fits.map(f => { const s = at(f.k.steps, t); return atRisk(f.rows, t) === 0 ? 'NE' : `${pct(s.S)} (${pct(s.t ? s.lo : 1)}, ${pct(s.t ? s.hi : 1)})` })])
  if (lr) R.push([`${fits[1].a} vs ${fits[0].a}`, '', '', 's'], ['   Hazard ratio (95% CI)', '', `${lr.hr.toFixed(2)} (${lr.hrlo.toFixed(2)}, ${lr.hrhi.toFixed(2)})`],
    ['   Log-rank p-value', '', lr.p < 0.0001 ? '<0.0001' : lr.p.toFixed(4)])
  return R
}

export function planToc(manifest, data) {
  let page = 3; return manifest.filter(o => o.include).map(o => { const e = { ...o, page, pages: pagesOf(o, data) }; page += e.pages; return e })
}

export async function buildPdf(manifest, data, shell) {
  const toc = planToc(manifest, data), lms = shell.landmarks.split(/[,\s]+/).map(Number).filter(n => n > 0).sort((a, b) => a - b)
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'letter' }), W = 792, H = 612, M = 48
  const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ')
  // Title page
  doc.setFont('courier', 'bold').setFontSize(20).text('XNB-301 Shell Package — KM Time-to-Event Outputs', W / 2, 200, { align: 'center' })
  doc.setFont('courier', 'normal').setFontSize(12)
  ;['Protocol XNB-301 · Phase 3 · ' + shell.arms.join(' vs '), 'ALL DATA ARE MOCK — seeded synthetic ADTTE, not a real study', `Data cutoff 30JUN2026 · Package built ${stamp} UTC`, `${toc.length} outputs · generated by TFL Shell Studio (demo)`]
    .forEach((l, i) => doc.text(l, W / 2, 250 + i * 22, { align: 'center' }))
  // TOC
  doc.addPage(); doc.setFont('courier', 'bold').setFontSize(14).text('Table of Contents', M, 80)
  doc.setFontSize(10).text('Output', M, 108); doc.text('Title', M + 130, 108); doc.text('Page', W - M, 108, { align: 'right' }); doc.line(M, 113, W - M, 113)
  doc.setFont('courier', 'normal')
  toc.forEach((e, i) => { const y = 132 + i * 20, label = `${e.kind} ${e.number}`
    doc.setTextColor(20, 60, 160); doc.text(label, M, y); doc.text(`${e.title} (${e.param === 'ALL' ? 'OS, PFS' : e.param})`.slice(0, 80), M + 130, y)
    doc.text(String(e.page), W - M, y, { align: 'right' }); doc.setTextColor(0); doc.link(M, y - 10, W - 2 * M, 14, { pageNumber: e.page }) })
  doc.outline.add(null, 'Title page', { pageNumber: 1 }); doc.outline.add(null, 'Table of Contents', { pageNumber: 2 })
  for (const e of toc) {
    doc.addPage(); doc.setDrawColor(0); doc.outline.add(null, `${e.kind} ${e.number} ${e.title}`, { pageNumber: e.page })
    const head = (cont) => { doc.setFont('courier', 'bold').setFontSize(11).text(`${e.kind} ${e.number}${cont ? ' (continued)' : ''}`, W / 2, 62, { align: 'center' })
      doc.text(e.title, W / 2, 76, { align: 'center' }); doc.setFont('courier', 'normal').setFontSize(10).text(e.pop, W / 2, 90, { align: 'center' }) }
    head(false)
    if (e.kind === 'Table') {
      const fits = fitsFor(data, e.param, shell), lr = fits.length === 2 && shell.logrank ? logrank(fits[0].rows, fits[1].rows) : null
      const rows = tableRows(fits, lms, lr), cx = [M, 400, 600]; let y = 120
      doc.setLineWidth(1.2).line(M, y - 14, W - M, y - 14)
      rows.forEach(r => { const st = r[r.length - 1], cells = st === 'h' || st === 's' ? r.slice(0, -1) : r
        doc.setFont('courier', st ? 'bold' : 'normal'); if (st === 's') y += 6
        cells.forEach((c, j) => doc.text(c, j ? cx[j] : M, y, { align: j ? 'center' : 'left' }))
        if (st === 'h') { doc.setLineWidth(.6).line(M, y + 6, W - M, y + 6); y += 6 } y += 17 })
      doc.setLineWidth(1.2).line(M, y - 8, W - M, y - 8)
    } else if (e.kind === 'Figure') {
      const fits = fitsFor(data, e.param, shell), lr = fits.length === 2 && shell.logrank ? logrank(fits[0].rows, fits[1].rows) : null
      const host = document.createElement('div'); host.style.cssText = 'position:absolute;left:-9999px;width:760px'
      host.innerHTML = renderToStaticMarkup(<Plot fits={fits} bands={shell.bands} step={shell.step} lr={lr} param={e.param} />); document.body.appendChild(host)
      const svg = host.querySelector('svg'); svg.setAttribute('font-family', 'helvetica'); svg.setAttribute('font-size', '11')
      await svg2pdf(svg, doc, { x: M + 40, y: 100, width: W - 2 * M - 80, height: (W - 2 * M - 80) * (380 + fits.length * 20 + 30) / 760 }); host.remove()
    } else {
      const rows = listingRows(data), cx = [M, 165, 290, 350, 430, 510, 570, 620]
      for (let p = 0; p * PER_PAGE < rows.length; p++) {
        if (p) { doc.addPage(); doc.setDrawColor(0); head(true) }
        let y = 116; doc.setFont('courier', 'bold').setFontSize(8.5); LIST_COLS.forEach((c, j) => doc.text(c, cx[j], y)); doc.line(M, y + 4, W - M, y + 4)
        doc.setFont('courier', 'normal'); rows.slice(p * PER_PAGE, (p + 1) * PER_PAGE).forEach(r => { y += 15; LIST_COLS.forEach((c, j) => doc.text(c === 'AVAL' ? r[c].toFixed(2) : String(r[c]), cx[j], y)) })
      }
    }
    // footnotes on each output's first page
    doc.setPage(e.page); doc.setFont('courier', 'normal').setFontSize(7.5)
    const notes = (e.kind === 'Listing' ? ['Listing excerpt: all ADTTE records for the first 40 subjects by USUBJID. CNSR: 0 = event, 1 = censored.'] : shell.foot.split('\n'))
      .concat(`Source: ADTTE (mock, seeded). Data cutoff 30JUN2026. Program: ${e.kind === 'Figure' ? 'f_km.R' : e.kind === 'Table' ? 't_km.R' : 'l_adtte.R'}`)
    notes.forEach((l, i) => doc.text(l, M, H - 70 + i * 10)); doc.setPage(doc.getNumberOfPages())
  }
  const N = doc.getNumberOfPages()
  for (let p = 1; p <= N; p++) { doc.setPage(p); doc.setFont('courier', 'normal').setFontSize(8).setTextColor(0).setDrawColor(0)
    doc.text(STUDY, M, 32); doc.setTextColor(200, 60, 15).text('MOCK DATA — NOT A REAL STUDY', W / 2, 32, { align: 'center' }); doc.setTextColor(0)
    doc.text(`Page ${p} of ${N}`, W - M, 32, { align: 'right' }); doc.line(M, 38, W - M, 38); doc.line(M, H - 34, W - M, H - 34)
    doc.text(`TFL Shell Studio shell package · built ${stamp} UTC`, M, H - 22) }
  doc.save('XNB-301_shell_package_MOCK.pdf')
}

const dl = (name, text, type) => { const a = document.createElement('a'); a.href = URL.createObjectURL(new Blob([text], { type })); a.download = name; a.click() }
const csv = toc => 'Output,Number,Title,Parameter,Population,Page\n' + toc.map(e => [e.kind, e.number, e.title, e.param, e.pop, e.page].map(v => `"${String(v).replace(/"/g, '""')}"`).join(',')).join('\n') + '\n'
const rtf = toc => `{\\rtf1\\ansi\\deff0{\\fonttbl{\\f0 Courier New;}}\\f0\\fs20{\\b XNB-301 Shell Package (MOCK) - Table of Contents}\\par\\par\n` +
  toc.map(e => `${e.kind} ${e.number}\\tab ${e.title.replace(/[\\{}]/g, '')}\\tab ${e.page}\\par`).join('\n') + '\n}'

export function PackagePanel({ data, shell }) {
  const [man, setMan] = useState(DEFAULT_MANIFEST), [busy, setBusy] = useState(false)
  const upd = (i, k, v) => setMan(m => m.map((o, j) => j === i ? { ...o, [k]: v } : o))
  const move = (i, d) => setMan(m => { const n = [...m], j = i + d; if (j < 0 || j >= n.length) return m; [n[i], n[j]] = [n[j], n[i]]; return n })
  const toc = planToc(man, data)
  return <div className="page pkg">
    <div className="gridbar"><b>Shell package manifest</b> (mock) · {toc.length} of {man.length} outputs included · arms, landmarks, footnotes and options come from the shell spec</div>
    <table className="man"><thead><tr><th>Incl.</th><th>Order</th><th>Type</th><th>Number</th><th>Title</th><th>Param</th><th>Population</th></tr></thead><tbody>
      {man.map((o, i) => <tr key={o.id} className={o.include ? '' : 'off'}><td><input type="checkbox" checked={o.include} onChange={e => upd(i, 'include', e.target.checked)} /></td>
        <td><button onClick={() => move(i, -1)}>↑</button><button onClick={() => move(i, 1)}>↓</button></td><td>{o.kind}</td>
        <td><input value={o.number} onChange={e => upd(i, 'number', e.target.value)} size={8} /></td><td><input value={o.title} onChange={e => upd(i, 'title', e.target.value)} size={48} /></td>
        <td>{o.param === 'ALL' ? 'OS, PFS' : o.param}</td><td><input value={o.pop} onChange={e => upd(i, 'pop', e.target.value)} size={22} /></td></tr>)}</tbody></table>
    <h4>Table of contents (preview)</h4>
    <table className="tfl toc"><thead><tr><th>Output</th><th>Title</th><th>Pages</th></tr></thead><tbody>
      <tr><td>—</td><td>Title page</td><td>1</td></tr><tr><td>—</td><td>Table of Contents</td><td>2</td></tr>
      {toc.map(e => <tr key={e.id}><td>{e.kind} {e.number}</td><td>{e.title}</td><td>{e.page}{e.pages > 1 ? `–${e.page + e.pages - 1}` : ''}</td></tr>)}</tbody></table>
    <div className="actions"><button className="primary" disabled={busy || !toc.length || !shell.arms.length} onClick={async () => { setBusy(true); try { await buildPdf(man, data, shell) } finally { setBusy(false) } }}>
      {busy ? 'Building…' : 'Build package PDF'}</button>
      <button onClick={() => dl('XNB-301_TOC_MOCK.csv', csv(toc), 'text/csv')}>TOC as CSV</button>
      <button onClick={() => dl('XNB-301_TOC_MOCK.rtf', rtf(toc), 'application/rtf')}>TOC as RTF</button>
      <span className="hint">PDF: title page, linked TOC, PDF bookmarks, vector KM figures, header/footer with Page X of Y.</span></div>
  </div>
}
